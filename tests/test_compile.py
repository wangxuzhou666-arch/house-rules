class HeaderTest(CompileCase):
    def sources(self) -> list[str]:
        match = HEADER_RE.match(self.digest().splitlines()[0])
        self.assertIsNotNone(match, self.digest().splitlines()[0])
        return match.group("sources").split(", ")

    def sha12(self, name: str) -> str:
        return hashlib.sha256((self.repo / name).read_bytes()).hexdigest()[:12]

    def test_header_names_the_source_with_the_hash_of_its_bytes(self) -> None:
        self.write_config(rules_files=["rules.md"])
        self.cli_ok("compile")
        self.assertEqual(self.sources(), [f"rules.md@{self.sha12('rules.md')}"])

    def test_header_covers_every_source_in_layer_order_with_relative_paths(self) -> None:
        (self.repo / "docs").mkdir()
        self.write_rules("1. **[X.1]** Project rule.\n", name="docs/project.md")
        self.write_config(rules_files=["rules.md", "docs/project.md"])
        self.cli_ok("compile")
        self.assertEqual(self.sources(), [f"rules.md@{self.sha12('rules.md')}", f"docs/project.md@{self.sha12('docs/project.md')}"])

    def test_header_hash_changes_when_a_source_changes(self) -> None:
        self.write_rules("1. **[X.1]** Project rule.\n", name="project.md")
        self.write_config(rules_files=["rules.md", "project.md"])
        self.cli_ok("compile")
        before = self.sources()
        self.write_rules("1. **[X.1]** Project rule, reworded.\n", name="project.md")
        self.cli_ok("compile")
        after = self.sources()
        self.assertEqual(before[0], after[0])  # the untouched source keeps its hash
        self.assertNotEqual(before[1], after[1])
        self.assertEqual(after[1], f"project.md@{self.sha12('project.md')}")

    def test_whitespace_only_edit_of_a_source_changes_the_hash(self) -> None:
        self.write_config(rules_files=["rules.md"])
        self.cli_ok("compile")
        before = self.sources()
        self.write_rules(STYLE_RULES + "\n")
        self.cli_ok("compile")
        self.assertNotEqual(self.sources(), before)

    def test_a_source_outside_the_repo_is_named_relative_to_the_repo_root(self) -> None:
        outside = self.tmp / "shared-rules.md"
        outside.write_text(STYLE_RULES, encoding="utf-8")
        self.write_config(rules_files=["../shared-rules.md"])
        self.cli_ok("compile")
        self.assertEqual(self.sources(), [f"../shared-rules.md@{hashlib.sha256(outside.read_bytes()).hexdigest()[:12]}"])


