def clause(text: str, override: str | None = None) -> Clause:
    return Clause("P1.1", None, 1, text, override)


class ShortRuleTest(unittest.TestCase):
    def test_cuts_at_the_first_full_stop(self) -> None:
        self.assertEqual(short_rule(clause("Keep it flat. Then say why."), 90), "Keep it flat")

    def test_cuts_at_a_semicolon(self) -> None:
        self.assertEqual(short_rule(clause("Keep it flat; then say why"), 90), "Keep it flat")

    def test_cuts_at_the_cjk_full_stop(self) -> None:
        self.assertEqual(short_rule(clause("first\u3002second"), 90), "first")

    def test_cuts_at_the_cjk_semicolon(self) -> None:
        self.assertEqual(short_rule(clause("first\uff1bsecond"), 90), "first")

    def test_the_earliest_terminator_wins(self) -> None:
        self.assertEqual(short_rule(clause("a; b. c"), 90), "a")
        self.assertEqual(short_rule(clause("a. b; c"), 90), "a")
        self.assertEqual(short_rule(clause("a\uff1bb\u3002c"), 90), "a")

    def test_a_full_stop_inside_a_word_or_number_is_not_a_cut(self) -> None:
        self.assertEqual(short_rule(clause("use os.path for 1.5 and a;b"), 90), "use os.path for 1.5 and a;b")

    def test_a_final_full_stop_is_dropped(self) -> None:
        self.assertEqual(short_rule(clause("Keep it flat."), 90), "Keep it flat")
        self.assertEqual(short_rule(clause("Keep it flat;"), 90), "Keep it flat")

    def test_a_sentence_end_inside_ascii_brackets_is_not_a_cut(self) -> None:
        self.assertEqual(short_rule(clause("Keep it flat (see a; b. c) always; more"), 90), "Keep it flat (see a; b. c) always")
        self.assertEqual(short_rule(clause("Keep it flat [a; b] always; more"), 90), "Keep it flat [a; b] always")

    def test_a_sentence_end_inside_each_full_width_bracket_is_not_a_cut(self) -> None:
        for opener, closer in (("\uff08", "\uff09"), ("\u3010", "\u3011"), ("\u300c", "\u300d")):
            with self.subTest(opener=opener):
                text = f"head{opener}x\uff1by\u3002z{closer}tail\u3002more"
                self.assertEqual(short_rule(clause(text), 90), f"head{opener}x\uff1by\u3002z{closer}tail")

    def test_cutting_resumes_once_the_bracket_closes(self) -> None:
        self.assertEqual(short_rule(clause("a (b; c) d; e (f; g)"), 90), "a (b; c) d")

    def test_nested_brackets_are_followed(self) -> None:
        self.assertEqual(short_rule(clause("a (b [c; d] e; f) g; h"), 90), "a (b [c; d] e; f) g")
        self.assertEqual(short_rule(clause("a (b (c; d) e; f) g; h"), 90), "a (b (c; d) e; f) g")

    def test_an_unclosed_bracket_protects_the_rest_of_the_text(self) -> None:
        self.assertEqual(short_rule(clause("Keep (open; still open. more"), 90), "Keep (open; still open. more")

    def test_a_stray_closing_bracket_does_not_hide_the_next_cut(self) -> None:
        self.assertEqual(short_rule(clause("a) b; c"), 90), "a) b")

    def test_a_sentence_end_before_the_first_bracket_still_cuts(self) -> None:
        self.assertEqual(short_rule(clause("first; second (third; fourth)"), 90), "first")

    def test_trailing_colons_and_spaces_are_trimmed_after_the_cut(self) -> None:
        self.assertEqual(short_rule(clause("Allowed only in five cases:"), 90), "Allowed only in five cases")
        self.assertEqual(short_rule(clause("Allowed only in five cases\uff1a"), 90), "Allowed only in five cases")
        self.assertEqual(short_rule(clause("Allowed only in five cases : \uff1a "), 90), "Allowed only in five cases")
        self.assertEqual(short_rule(clause("Intro:; more"), 90), "Intro")

    def test_a_colon_inside_the_text_stays(self) -> None:
        self.assertEqual(short_rule(clause("Rule: keep it flat"), 90), "Rule: keep it flat")

    def test_the_cap_still_applies_after_the_trim_and_may_land_inside_a_bracket(self) -> None:
        self.assertEqual(short_rule(clause("ab (cd ef gh ij kl) mn:"), 8), "ab (cd" + ELLIPSIS)  # text[:7] is "ab (cd ", cut inside the open bracket

    def test_an_override_is_not_trimmed(self) -> None:
        self.assertEqual(short_rule(clause("ignored", "Use this:"), 90), "Use this:")

    def test_bold_markers_go_and_backticks_stay(self) -> None:
        self.assertEqual(short_rule(clause("Use **only** `except ValueError` here"), 90), "Use only `except ValueError` here")

    def test_the_cap_ends_in_an_ellipsis_and_the_total_is_the_cap(self) -> None:
        result = short_rule(clause("x" * 100), 90)
        self.assertEqual(result, "x" * 89 + ELLIPSIS)
        self.assertEqual(len(result), 90)

    def test_text_exactly_at_the_cap_is_untouched(self) -> None:
        self.assertEqual(short_rule(clause("x" * 90), 90), "x" * 90)
        self.assertEqual(short_rule(clause("x" * 91), 90), "x" * 89 + ELLIPSIS)

    def test_the_cap_counts_characters_not_bytes(self) -> None:
        wide = "\u4e00" * 100  # 3 bytes each in UTF-8
        self.assertEqual(short_rule(clause(wide), 90), "\u4e00" * 89 + ELLIPSIS)
        self.assertEqual(short_rule(clause("\u4e00" * 90), 90), "\u4e00" * 90)

    def test_trailing_space_before_the_ellipsis_is_trimmed(self) -> None:
        self.assertEqual(short_rule(clause("word " * 30), 6), "word" + ELLIPSIS)  # text[:5] is "word "

    def test_the_cap_applies_after_the_cut(self) -> None:
        self.assertEqual(short_rule(clause("short. " + "x" * 200), 20), "short")

    def test_a_cut_inside_a_code_span_backs_off_to_just_before_the_span(self) -> None:
        result = short_rule(clause("x" * 50 + " `some_long_identifier_name` tail"), 70)
        self.assertEqual(result, "x" * 50 + ELLIPSIS)

    def test_the_back_off_drops_the_space_before_the_span(self) -> None:
        self.assertEqual(short_rule(clause("a" * 20 + "   `" + "b" * 40), 30), "a" * 20 + ELLIPSIS)

    def test_a_back_off_that_keeps_exactly_half_the_cap_is_taken(self) -> None:
        self.assertEqual(short_rule(clause("a" * 10 + " `very_long_identifier_here`"), 20), "a" * 10 + ELLIPSIS)

    def test_a_back_off_that_would_leave_less_than_half_the_cap_cuts_normally(self) -> None:
        text = "a" * 9 + " `very_long_identifier_here`"
        self.assertEqual(short_rule(clause(text), 20), text[:19] + ELLIPSIS)

    def test_only_the_open_span_is_backed_off_and_closed_spans_stay(self) -> None:
        self.assertEqual(short_rule(clause("Use `a` then `very_long_identifier_name` ok"), 24), "Use `a` then" + ELLIPSIS)

    def test_a_cut_right_after_the_closing_backtick_is_not_a_back_off(self) -> None:
        self.assertEqual(short_rule(clause("ab `cd` efghijklmnop"), 8), "ab `cd`" + ELLIPSIS)

    def test_spans_close_on_a_run_of_the_same_length(self) -> None:
        text = "x" * 20 + " ``a`b long code`` tail"
        self.assertEqual(short_rule(clause(text), 30), "x" * 20 + ELLIPSIS)  # the single backtick inside is text, not a closer

    def test_a_backed_off_rule_never_exceeds_the_cap(self) -> None:
        for cap in range(20, 60):
            with self.subTest(cap=cap):
                self.assertLessEqual(len(short_rule(clause("word " * 8 + "`" + "identifier_" * 6 + "` end"), cap)), cap)

    def test_an_override_wins_and_is_used_verbatim(self) -> None:
        override = "Hand-written form. With two sentences and **bold**, longer than the cap"
        self.assertEqual(short_rule(clause("Original wording that would be cut. Extra.", override), 10), override)


class InjectBlockTest(unittest.TestCase):
    def inject(self, text: str) -> str:
        return inject_block(text, "BLOCK\n", "CLAUDE.md")

    def test_replaces_everything_between_the_markers(self) -> None:
        text = f"before\n{BEGIN_MARKER}\nold\nold again\n{END_MARKER}\nafter\n"
        self.assertEqual(self.inject(text), f"before\n{BEGIN_MARKER}\nBLOCK\n{END_MARKER}\nafter\n")

    def test_empty_span_between_adjacent_markers(self) -> None:
        self.assertEqual(self.inject(f"{BEGIN_MARKER}{END_MARKER}"), f"{BEGIN_MARKER}\nBLOCK\n{END_MARKER}")

    def test_injecting_twice_changes_nothing(self) -> None:
        once = self.inject(f"a\n{BEGIN_MARKER}\n{END_MARKER}\nb\n")
        self.assertEqual(self.inject(once), once)

    def test_missing_begin_marker(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "CLAUDE.md: marker .*begin.* not found"):
            self.inject(f"text\n{END_MARKER}\n")

    def test_missing_end_marker(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "CLAUDE.md: marker .*end.* not found"):
            self.inject(f"text\n{BEGIN_MARKER}\nmore text\n")

    def test_no_markers_at_all(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "not found"):
            self.inject("plain text\n")

    def test_duplicated_begin_marker(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "appears 2 times"):
            self.inject(f"{BEGIN_MARKER}\n{BEGIN_MARKER}\n{END_MARKER}\n")

    def test_duplicated_end_marker(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "appears 2 times"):
            self.inject(f"{BEGIN_MARKER}\n{END_MARKER}\n{END_MARKER}\n")

    def test_end_marker_before_begin_marker(self) -> None:
        with self.assertRaisesRegex(HouseRulesError, "before the begin marker"):
            self.inject(f"{END_MARKER}\n{BEGIN_MARKER}\n")


class CompileCase(RepoCase):
    def setUp(self) -> None:
        super().setUp()
        self.write_rules(STYLE_RULES)

    def configure(self, **config: object) -> None:
        self.write_config(rules_files=["rules.md"], **config)

    def digest(self) -> str:
        return (self.repo / DIGEST_NAME).read_text(encoding="utf-8")

    def digest_lines(self, heading: str) -> list[str]:
        """The lines under a `## heading` of the digest, up to the next blank line."""
        lines = self.digest().splitlines()
        begin = lines.index(f"## {heading}") + 1
        end = lines.index("", begin)
        return lines[begin:end]

    def write_target(self, body: str = "", name: str = "CLAUDE.md") -> str:
        text = f"# Project notes\n\nkeep this\n\n{BEGIN_MARKER}\n{body}{END_MARKER}\n\nand keep this too\n"
        (self.repo / name).write_text(text, encoding="utf-8")
        return text

    def repo_files(self) -> dict[str, bytes]:
        return {str(p.relative_to(self.repo)): p.read_bytes()
                for p in sorted(self.repo.rglob("*")) if p.is_file() and ".git" not in p.relative_to(self.repo).parts}


class DigestContentTest(CompileCase):
    def setUp(self) -> None:
        super().setUp()
        self.configure()

    def test_writes_the_default_digest_at_the_repo_root(self) -> None:
        out = self.cli_ok("compile")
        self.assertTrue((self.repo / DIGEST_NAME).exists())
        self.assertIn(f"wrote {DIGEST_NAME}", out)

    def test_sections_come_in_order(self) -> None:
        self.cli_ok("compile")
        headings = [line for line in self.digest().splitlines() if line.startswith("## ")]
        self.assertEqual(headings, ["## Violations", "## Reviewer rules", "## Labeling"])

    def test_violation_lines_carry_id_severity_and_the_short_rule(self) -> None:
        self.cli_ok("compile")
        self.assertEqual(self.digest_lines("Violations"), [
            "P0E.1 | blocker | Keep the guarded `try` block to the one line expected to fail",
            "P0E.2 | blocker | Catch a specific type",
            "P0F.1 | blocker | Fail fast at the boundary",
            "P1.1 | should-fix | Nesting depth of five or more is a violation",
            "P2.1 | should-fix | One implementation does not need a base class",
            "P3.1 | nice | Explain why, not what",
        ])

    def test_families_outside_the_table_are_reviewer_rules_without_a_severity(self) -> None:
        self.cli_ok("compile")
        self.assertEqual(self.digest_lines("Reviewer rules"), [
            "R.1 | Standards come from this file, not from the reviewer",
            "R.2 | Never rubber-stamp a clean diff",
        ])

    def test_labeling_section_is_the_static_instruction(self) -> None:
        self.cli_ok("compile")
        labeling = self.digest().split("## Labeling\n", 1)[1]
        for phrase in ("kebab-case", "`P0E.6` -> `p0e-6`", "`unmapped`", "Prefer `unmapped` over stretching a clause",
                       "one finding per defect", "instead of filing duplicates"):
            self.assertIn(phrase.lower(), labeling.lower())

    def test_labeling_makes_the_two_keys_mandatory_for_every_finding_object(self) -> None:
        self.cli_ok("compile")
        labeling = self.digest().split("## Labeling\n", 1)[1]
        self.assertIn("JSON array", labeling)
        self.assertIn("every finding object MUST carry two keys", labeling)
        self.assertIn('- `"category"`:', labeling)
        self.assertIn('- `"severity"`:', labeling)
        for severity in ("blocker", "should-fix", "nice"):
            self.assertIn(f"`{severity}`", labeling)

    def test_the_labeling_example_is_a_finding_the_ingest_command_labels_as_the_model_did(self) -> None:
        self.cli_ok("compile")
        labeling = self.digest().split("## Labeling\n", 1)[1]
        (line,) = [line for line in labeling.splitlines() if line.startswith("Example: ")]
        example = json.loads(line.removeprefix("Example: ").strip("`"))
        self.assertEqual(set(example), {"file", "line", "summary", "failure_scenario", "category", "severity"})
        self.cli_ok("ingest-code-review", "--source", "l1", "--run", "R1", stdin=json.dumps([example]))
        (event,) = self.events()
        self.assertEqual((event["rule_id"], event["rule_id_source"], event["severity"]), ("P0E.2", "model", "blocker"))

    def test_a_clause_tag_overrides_the_family_and_a_tagged_clause_is_a_violation(self) -> None:
        self.write_rules("1. **[P3.1]** Style nit (blocker)\n2. **[R.1]** Guidance\n3. **[R.2]** Tagged guidance (nice)\n")
        self.cli_ok("compile")
        self.assertEqual(self.digest_lines("Violations"), ["P3.1 | blocker | Style nit", "R.2 | nice | Tagged guidance"])
        self.assertEqual(self.digest_lines("Reviewer rules"), ["R.1 | Guidance"])

    def test_without_a_severity_table_everything_is_a_reviewer_rule_and_compile_warns(self) -> None:
        self.write_rules("1. **[P1.1]** One\n2. **[R.1]** Two\n")
        code, _, err = self.cli("compile")
        self.assertEqual(code, 0)
        self.assertIn("no clause has a severity", err)
        self.assertEqual(self.digest_lines("Violations"), ["(none)"])
        self.assertEqual(self.digest_lines("Reviewer rules"), ["P1.1 | One", "R.1 | Two"])

    def test_digest_max_chars_comes_from_the_config(self) -> None:
        self.configure(digest_max_chars=12)
        self.cli_ok("compile")
        self.assertIn("P0F.1 | blocker | Fail fast a" + ELLIPSIS + "\n", self.digest())

    def test_override_comment_replaces_the_extracted_text(self) -> None:
        self.write_rules("1. **[P1.1]** Long original wording here. <!-- digest: Flat code only -->\n\n" + SEVERITY_TABLE)
        self.cli_ok("compile")
        self.assertEqual(self.digest_lines("Violations"), ["P1.1 | should-fix | Flat code only"])

    def test_a_parenthetical_with_a_semicolon_survives_and_a_trailing_colon_goes(self) -> None:
        self.write_rules("1. **[P0E.5]** Log with `logger.exception` (the other form drops the traceback; see the linter). Done.\n"
                         "2. **[P0E.3]** `except Exception` is legal only in five cases:\n"
                         "   - first case\n\n" + SEVERITY_TABLE)
