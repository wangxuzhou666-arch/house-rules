class InjectTest(CompileCase):
    def setUp(self) -> None:
        super().setUp()
        self.write_config(rules_files=["rules.md"], inject_targets=["CLAUDE.md"])

    def claude(self) -> str:
        return (self.repo / "CLAUDE.md").read_text(encoding="utf-8")

    def test_block_is_written_between_the_markers_and_the_rest_is_kept(self) -> None:
        self.write_target()
        self.cli_ok("compile")
        text = self.claude()
        self.assertTrue(text.startswith("# Project notes\n\nkeep this\n\n" + BEGIN_MARKER + "\n"))
        self.assertTrue(text.endswith(END_MARKER + "\n\nand keep this too\n"))
        block = text.split(BEGIN_MARKER + "\n", 1)[1].split(END_MARKER, 1)[0]
        self.assertTrue(block.startswith("<!-- generated by house-rules compile from rules.md@"))
        for heading in ("## Violations", "## Reviewer rules", "## Labeling"):
            self.assertIn(heading, block)
        self.assertIn("P0E.2 | blocker | Catch a specific type", block)
        self.assertNotIn("# Style digest", block)

    def test_block_has_the_same_three_sections_as_the_digest(self) -> None:
        self.write_target()
        self.cli_ok("compile")
        block = self.claude().split(BEGIN_MARKER + "\n", 1)[1].split(END_MARKER, 1)[0]
        self.assertEqual(block.split("\n", 1)[1], self.digest().split("# Style digest\n\n", 1)[1])

