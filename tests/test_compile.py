class IngestUsesTheTableTest(RepoCase):
    """`ingest-code-review` and `add` fall back to the family table when the reviewer gave no severity."""

    def setUp(self) -> None:
        super().setUp()
        self.write_rules(STYLE_RULES)
        self.write_config(rules_files=["rules.md"])

    def severities(self, categories: list[str]) -> list[str]:
        items = [{"file": "src/a.py", "line": number, "summary": "synthetic", "failure_scenario": "synthetic", "category": category}
                 for number, category in enumerate(categories, start=1)]
        self.cli_ok("ingest-code-review", "--source", "l1", "--run", "R1", stdin=json.dumps(items))
        return [event["severity"] for event in self.events()]

    def test_missing_severity_comes_from_the_family_table(self) -> None:
        self.assertEqual(self.severities(["p0e-1", "p0f-1", "p1-1", "p2-1", "p3-1"]),
                         ["blocker", "blocker", "should-fix", "should-fix", "nice"])

    def test_a_family_outside_the_table_and_unmapped_fall_back_to_should_fix(self) -> None:
        self.assertEqual(self.severities(["r-1", "no-such-clause"]), ["should-fix", "should-fix"])

    def test_a_given_severity_still_wins_over_the_table(self) -> None:
        items = [{"file": "src/a.py", "line": 1, "summary": "s", "failure_scenario": "f", "category": "p0e-1", "severity": "nice"}]
        self.cli_ok("ingest-code-review", "--source", "l1", "--run", "R1", stdin=json.dumps(items))
        self.assertEqual(self.events()[0]["severity"], "nice")

    def test_add_without_a_severity_uses_the_table(self) -> None:
        item = {"id": "R1-001", "file": "src/a.py", "line": 1, "summary": "s", "failure_scenario": "f", "verdict": "PLAUSIBLE",
                "rule_id": "P3.1"}
        self.cli_ok("add", "--source", "l1", "--run", "R1", stdin=json.dumps([item]))
        self.assertEqual(self.events()[0]["severity"], "nice")


